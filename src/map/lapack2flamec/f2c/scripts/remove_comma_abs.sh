#!/bin/bash

main() 
{
    # local variables
    script_name=${0##*/}
    src_dir="../c"

    echo " "
    echo " "
    echo " "${script_name}
    echo " "
    echo " Objective:"
    echo "   The script removes comma expressions, which are automatically generated by abs macro."
    echo " "

    files="$(find ${src_dir} -maxdepth 1 -name "*.c")"
    for file in ${files}; do
        echo -ne "   Removing comma expressions from ... ${file}                  "\\r

        tmp_file=$(echo "${src_dir}/${file}.back")
        ( mv -f ${src_dir}/${file} ${src_dir}/${tmp_file} ;
            cat ${src_dir}/${tmp_file} \
                | sed  's/\([ a-z0-9_]*\) = \([][ &a-z0-9_/<>.,+*()-]*\), abs([ a-z0-9_]*)/(abs(\2))/g' \
                > ${src_dir}/${file} ;
            rm -f ${src_dir}/${tmp_file} )
    done

    return 0
}

main "$@"


